// raw CAL0 battery version (0x4310) and the 8th character of the CAL0 battery lot (0x2CE7): BDF main.asm 0x1354.
inline auto ChooseTable(int cal0_version, char vendor) -> const Table& {
    if (cal0_version == 1) {
        return TABLE_1;
    }
    if (cal0_version == 2) {
        return vendor == 'M' ? TABLE_2M : vendor == 'R' ? TABLE_2R : TABLE_2A;
    }
    return vendor == 'M' ? TABLE_0M : vendor == 'R' ? TABLE_0R : TABLE_0A;
}

// RemCap / RepCap after the init: FullCap * VFSOC / 25600, in 32 bits (16 x 16 overflows u16).
inline auto RemCap(std::uint16_t fullcap, std::uint16_t vfsoc) -> std::uint16_t {
    return static_cast<std::uint16_t>(static_cast<std::uint32_t>(fullcap) * vfsoc / 25600u);
}

enum class Op {
    Read,        // read reg into the named slot
    Write,       // plain write (5 tries)
    Verify,      // write, read back, up to 8 rounds
    Sleep,       // value = milliseconds
};
enum class Src {
    Const,       // `value`
    Table,       // table[value]
    MiscOr15,    // the MiscCFG read in step 1 | 0x8000
    VfSoc,       // first VFSOC read
    VfSoc2,      // second VFSOC read (BDF writes it to QH0)
    RemCap,      // RemCap(table[2], VFSOC)
    FullCapQ,    // table[2] >> 4
};
enum Slot { SLOT_MISC = 0, SLOT_VFSOC = 1, SLOT_VFSOC2 = 2 };

struct Step {
    Op op;
    std::uint8_t reg;
    Src src;
    std::uint16_t value; // constant, table index, slot or milliseconds
};

// FINDINGS §5 steps 1..44, the 48 model words expanded into step 12.
inline auto FactoryInitSteps() -> std::vector<Step> {
    std::vector<Step> s{
        {Op::Read, 0x2B, Src::Const, SLOT_MISC},
        {Op::Write, 0x2B, Src::MiscOr15, 0},
        {Op::Sleep, 0, Src::Const, 500},
        {Op::Write, 0x1D, Src::Const, 0x7210},
        {Op::Write, 0x29, Src::Const, 0x8784},
        {Op::Write, 0x2A, Src::Const, 0x203B},
        {Op::Write, 0x28, Src::Const, 0x2603},
        {Op::Write, 0x13, Src::Table, 3},
        {Op::Write, 0x36, Src::Table, 4},
        {Op::Write, 0x62, Src::Const, 0x0059},
        {Op::Write, 0x63, Src::Const, 0x00C4},
    };
    for (std::uint8_t i = 0; i < 48; i++) {
        s.push_back({Op::Verify, static_cast<std::uint8_t>(0x80 + i), Src::Table, static_cast<std::uint16_t>(9 + i)});
    }
    const std::vector<Step> rest{
        {Op::Write, 0x62, Src::Const, 0x0000},
        {Op::Write, 0x63, Src::Const, 0x0000},
        {Op::Verify, 0x38, Src::Table, 0},
        {Op::Verify, 0x39, Src::Table, 1},
        {Op::Write, 0x1E, Src::Const, 0x0333},
        {Op::Write, 0x2C, Src::Const, 0xE1F6},
        {Op::Write, 0x2D, Src::Const, 0x2BF2},
        {Op::Verify, 0x3A, Src::Const, 0xA05F},
        {Op::Verify, 0x12, Src::Table, 5},
        {Op::Verify, 0x22, Src::Table, 6},
        {Op::Verify, 0x32, Src::Table, 7},
        {Op::Verify, 0x42, Src::Table, 8},
        {Op::Verify, 0x10, Src::Table, 2},
        {Op::Write, 0x18, Src::Table, 2},
        {Op::Verify, 0x23, Src::Table, 2},
        {Op::Sleep, 0, Src::Const, 350},
        {Op::Read, 0xFF, Src::Const, SLOT_VFSOC},
        {Op::Write, 0x60, Src::Const, 0x0080},
        {Op::Write, 0x48, Src::VfSoc, 0},
        {Op::Read, 0xFF, Src::Const, SLOT_VFSOC2},
        {Op::Write, 0x4C, Src::VfSoc2, 0},
        {Op::Write, 0x60, Src::Const, 0x0000},
        {Op::Verify, 0x17, Src::Const, 0x0060},
        {Op::Verify, 0x0F, Src::RemCap, 0},
        {Op::Verify, 0x05, Src::RemCap, 0},
        {Op::Verify, 0x46, Src::Const, 0x0C80},
        {Op::Verify, 0x45, Src::FullCapQ, 0},
        {Op::Verify, 0x10, Src::Table, 2},
        {Op::Write, 0x18, Src::Table, 2},
        {Op::Verify, 0x23, Src::Table, 2},
        {Op::Write, 0x06, Src::VfSoc, 0},
        {Op::Verify, 0x00, Src::Const, 0x0000},
        {Op::Write, 0x2E, Src::Const, 0x7FFF},
        {Op::Write, 0x3F, Src::Const, 0xE000},
        {Op::Write, 0x1B, Src::Const, 0x00FF},
    };
    s.insert(s.end(), rest.begin(), rest.end());
    return s;
}

// the value a write step puts in the chip
inline auto StepValue(const Step& st, const Table& t, const std::array<std::uint16_t, 3>& slots) -> std::uint16_t {
    switch (st.src) {
        case Src::Const: return st.value;
        case Src::Table: return t[st.value];
        case Src::MiscOr15: return static_cast<std::uint16_t>(slots[SLOT_MISC] | 0x8000);
        case Src::VfSoc: return slots[SLOT_VFSOC];
        case Src::VfSoc2: return slots[SLOT_VFSOC2];
        case Src::RemCap: return RemCap(t[2], slots[SLOT_VFSOC]);
        case Src::FullCapQ: return static_cast<std::uint16_t>(t[2] >> 4);
    }
    return 0;
}

