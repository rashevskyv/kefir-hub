// Text for the language of the page (?lang=uk, default English). Counts %s / %d in order.
var LANG = (new URLSearchParams(location.search).get("lang") === "uk") ? "uk" : "en";
var USED_NEW = {};
function TX(key) {
  var text = key;
  if (LANG === "uk") {
    if (HUB[key] !== undefined) text = HUB[key];
    else if (NEW[key] !== undefined) text = NEW[key];
  }
  if (NEW[key] !== undefined) USED_NEW[key] = true;
  for (var i = 1; i < arguments.length; i++) text = text.replace(/%[sd]/, String(arguments[i]));
  return text.replace(/%%/g, "%");
}
